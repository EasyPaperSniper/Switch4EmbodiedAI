def compute_dtw_per_second(row):
    """Compute DTW normalized by duration (DTW per second)"""
    if pd.notna(row['pa_mpjpe_dtw']) and pd.notna(row['duration_sec']) and row['duration_sec'] > 0:
        return row['pa_mpjpe_dtw']
    return None

