def load_all_csv_files(base_dir):
    """
    Discover and load all alignment_results.csv files from the directory structure.
    
    Returns:
        DataFrame with columns: person, song, condition, pa_mpjpe, mpjpe, dtw, etc.
    """
    csv_files = glob(str(base_dir / "**" / "alignment_results.csv"), recursive=True)
    
    all_data = []
    
    for csv_file in csv_files:
        # Parse path to extract person, song, condition
        # Path structure: .../Person/Song/Song_Person_condition/alignment_results.csv
        path_parts = pathlib.Path(csv_file).parts
        
        # Find the person directory (should be a few levels up)
        try:
            # Get the parent directory name (e.g., "Old_Town_Road_WT_normal_1")
            recording_dir = pathlib.Path(csv_file).parent.name
            
            # Parse the recording directory name
            # Format: SongName_PersonName_condition
            parts = recording_dir.rsplit('_', 2)  # Split from right to get last 2 underscores
            if len(parts) >= 3:
                condition_type = parts[-2]  # e.g., "normal"
                condition_num = parts[-1]   # e.g., "1"
                condition = f"{condition_type}_{condition_num}"
                
                # Find person from path
                person_dir = pathlib.Path(csv_file).parent.parent.parent.name
                person = PERSON_NAME_MAPPING.get(person_dir, person_dir)
                
                # Find song from path
                song_dir = pathlib.Path(csv_file).parent.parent.name
                song = song_dir
                
                # Read CSV file
                df = pd.read_csv(csv_file)
                
                # Take only the last row (most recent run) if multiple rows exist
                # This handles cases where CSV was appended to multiple times
                if len(df) > 0:
                    row = df.iloc[-1]  # Take last row
                    
                    all_data.append({
                        'person': person,
                        'song': song,
                        'condition': condition,
                        'pa_mpjpe': row.get('pa_mpjpe', None),
                        'mpjpe': row.get('mpjpe', None),
                        'pa_mpjpe_dtw': row.get('pa_mpjpe_dtw', None),
                        'dtw_total_cost': row.get('dtw_total_cost', None),
                        'dtw_path_length': row.get('dtw_path_length', None),
                        'duration_sec': row.get('duration_sec', None),
                        'position_velocity_error_mean': row.get('position_velocity_error_mean', None),
                        'position_acceleration_error_mean': row.get('position_acceleration_error_mean', None),
                        'csv_path': csv_file
                    })
                    
                    if len(df) > 1:
                        print(f"Loaded: {person} / {song} / {condition} (used last of {len(df)} rows)")
                    else:
                        print(f"Loaded: {person} / {song} / {condition}")
        except Exception as e:
            print(f"Error parsing {csv_file}: {e}")
            continue
    
    return pd.DataFrame(all_data)

